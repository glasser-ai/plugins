import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync, existsSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const read = (name) => JSON.parse(readFileSync(path.join(root, name), "utf8"));
const portable = read("plugin.json");
const overlay = read(".codex-plugin/plugin.json");
assert.equal(portable.$schema, "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json");
assert.equal(portable.name, "glasser-prospect-lists");
assert.equal(portable.version, overlay.version);
const { interface: ui, review } = portable.extensions["com.openai"];
assert.deepEqual(ui, overlay.interface);
assert.deepEqual(review, overlay.extensions["com.openai"].review);
assert(ui.shortDescription.length <= 30);
assert(!/balance|credits|pay per|subscription|pricing/i.test([portable.description, ui.longDescription, ui.shortDescription].join(" ")));
assert.equal(review.test_cases.positive.length, 5);
assert.equal(review.test_cases.negative.length, 3);
for (const sample of review.test_cases.positive) {
  assert(sample.description && sample.prompt && sample.tools_triggered && sample.expected_behavior);
}
for (const key of ["composerIcon", "logo", "logoDark"]) assert(existsSync(path.join(root, ui[key])));
const mcp = read("mcp.json");
assert.equal(mcp.$schema, "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json");
const server = mcp.mcpServers["glasser-prospect"];
assert.equal(server.type, "streamable-http");
assert.equal(new URL(server.url).searchParams.get("toolset"), "prospect");
assert.equal(server.url, read(".mcp.json").mcpServers["glasser-prospect"].url);
const skill = readFileSync(path.join(root, "skills/prospect-list/SKILL.md"), "utf8");
assert(skill.startsWith("---\nname: prospect-list\n"));
assert(!/npm install|npx |install it first|glasser\.ai\/SKILL\.md|app\.glasser\.ai\/balance/i.test(skill));
for (const field of ["email_verified_date", "matched_filters", "resolved_from", "phone_source"]) assert(skill.includes(field));
const output = path.resolve(root, "../glasser-prospect-lists-openai.zip");
rmSync(output, { force: true });
execFileSync("zip", ["-r", "-X", output, "plugin.json", "mcp.json", ".mcp.json", ".codex-plugin", "skills", "assets", "LICENSE"], { cwd: root, stdio: "ignore" });
const entries = execFileSync("unzip", ["-Z1", output], { encoding: "utf8" }).trim().split("\n");
for (const file of ["plugin.json", "mcp.json", "skills/prospect-list/SKILL.md", ".codex-plugin/plugin.json"]) assert(entries.includes(file));
assert(!entries.some((file) => /(^|\/)(?:\.env|node_modules|__MACOSX|\.DS_Store)/.test(file)));
console.log(`Validated ${portable.name} ${portable.version}; ${entries.length} ZIP entries: ${output}`);
